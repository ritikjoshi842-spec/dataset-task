import io
import datetime
from xml.sax.saxutils import escape
from typing import Dict

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image, KeepTogether, PageBreak
)
from reportlab.pdfgen import canvas

from backend.dataset import DatasetContext
from backend.schemas import ReportDraft, ToolResult
from backend.viz.mpl_engine import render_mpl

class NumberedCanvas(canvas.Canvas):
    """Canvas to add running header and footer with total page counts."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#718096"))
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "Data Analytics Tool — Automated Analysis Report")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, 744, 558, 744)
            
        # Footer
        footer_text = "Generated by Data Analytics Tool — figures computed with Pandas/NumPy"
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawString(54, 36, footer_text)
        self.drawRightString(558, 36, page_str)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 46, 558, 46)
        
        self.restoreState()

def build_pdf_report(draft: ReportDraft, ctx: DatasetContext, tool_results: Dict[str, ToolResult]) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )
    
    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=26,
        textColor=colors.HexColor("#1A202C"),
        spaceAfter=6
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#4A5568"),
        spaceAfter=15
    )
    
    h1_style = ParagraphStyle(
        'Heading1_Custom',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#2B6CB0"),
        spaceBefore=14,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'Body_Custom',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=13.5,
        textColor=colors.HexColor("#2D3748"),
        spaceAfter=6
    )
    
    caption_style = ParagraphStyle(
        'Caption_Custom',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#718096"),
        alignment=1, # Centered
        spaceAfter=8
    )

    story = []
    
    # 1. Header & Title
    story.append(Paragraph(escape(draft.title), title_style))
    date_str = datetime.datetime.now().strftime("%B %d, %Y")
    subtitle_text = f"Dataset: <b>{escape(ctx.name)}</b> | Dimensions: <b>{ctx.n_rows:,} rows × {ctx.n_cols} columns</b> | Date: <b>{date_str}</b>"
    story.append(Paragraph(subtitle_text, subtitle_style))
    story.append(Spacer(1, 8))
    
    # 2. Executive Summary Box
    summary_html = f"<b>Executive Summary:</b><br/>{escape(draft.executive_summary)}"
    summary_table = Table(
        [[Paragraph(summary_html, body_style)]],
        colWidths=[504]
    )
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#EDF2F7")),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#CBD5E0")),
        ('TOPPADDING', (0,0), (-1,-1), 8),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
        ('LEFTPADDING', (0,0), (-1,-1), 10),
        ('RIGHTPADDING', (0,0), (-1,-1), 10),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 12))

    # 2b. Plain-English Non-Technical Guide (What This Dataset Is About & What It Tells Us)
    if getattr(draft, "plain_english_guide", None):
        story.append(Paragraph("What This Dataset Is About & What We Can Learn From It (Plain-English Guide)", h1_style))
        guide_paragraphs = [p.strip() for p in draft.plain_english_guide.split("\n\n") if p.strip()]
        guide_flowables = []
        for idx, para in enumerate(guide_paragraphs):
            clean_para = escape(para).replace("\n", "<br/>")
            guide_flowables.append(Paragraph(clean_para, body_style))
            if idx < len(guide_paragraphs) - 1:
                guide_flowables.append(Spacer(1, 4))
        
        guide_box = Table(
            [[guide_flowables]],
            colWidths=[504]
        )
        guide_box.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F0FFF4")),
            ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#9AE6B4")),
            ('TOPPADDING', (0,0), (-1,-1), 10),
            ('BOTTOMPADDING', (0,0), (-1,-1), 10),
            ('LEFTPADDING', (0,0), (-1,-1), 12),
            ('RIGHTPADDING', (0,0), (-1,-1), 12),
        ]))
        story.append(guide_box)
        story.append(Spacer(1, 14))

    # 3. Dataset Overview Table
    story.append(Paragraph("Dataset Overview & Schema Summary", h1_style))
    schema_data = [["Column", "Inferred Type", "Non-Null %", "Unique Values"]]
    for col_name, info in list(ctx.schema.items())[:15]:
        non_null_pct = f"{100 - info.null_pct:.1f}%"
        schema_data.append([
            Paragraph(escape(col_name), body_style),
            Paragraph(escape(info.semantic_type), body_style),
            Paragraph(non_null_pct, body_style),
            Paragraph(f"{info.nunique:,}", body_style)
        ])
    
    schema_table = Table(schema_data, colWidths=[180, 110, 100, 114], repeatRows=1)
    schema_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#2B6CB0")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,0), 9),
        ('BOTTOMPADDING', (0,0), (-1,0), 5),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor("#F7FAFC")]),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#E2E8F0")),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
    ]))
    story.append(schema_table)
    story.append(Spacer(1, 14))

    # 4. Sections & Findings with Charts
    for section in draft.sections:
        sec_flowables = []
        sec_flowables.append(Paragraph(escape(section.heading), h1_style))
        if section.body_markdown:
            sec_flowables.append(Paragraph(escape(section.body_markdown), body_style))
            
        for f in section.findings:
            finding_text = f"• <b>{escape(f.statement)}</b>"
            if f.confidence_note:
                finding_text += f" <i>({escape(f.confidence_note)})</i>"
            sec_flowables.append(Paragraph(finding_text, body_style))
            
        # Render charts for this section
        for spec in section.chart_specs:
            try:
                img_bytes = render_mpl(spec, ctx, tool_results)
                img_buf = io.BytesIO(img_bytes)
                img = Image(img_buf, width=360, height=195)
                img.hAlign = 'CENTER'
                sec_flowables.append(Spacer(1, 6))
                sec_flowables.append(img)
                sec_flowables.append(Paragraph(f"Figure: {escape(spec.title)}", caption_style))
            except Exception as e:
                pass
                
        sec_flowables.append(Spacer(1, 10))
        story.append(KeepTogether(sec_flowables))

    # 5. Recommendations
    if draft.recommendations:
        rec_flowables = [Paragraph("Recommendations", h1_style)]
        for rec in draft.recommendations:
            rec_flowables.append(Paragraph(f"✓ {escape(rec)}", body_style))
        rec_flowables.append(Spacer(1, 10))
        story.append(KeepTogether(rec_flowables))

    # 6. Limitations & Analyses Not Performed
    limitations_all = list(draft.limitations)
    if draft.not_performed:
        limitations_all.extend([f"Skipped: {np}" for np in draft.not_performed])
        
    if limitations_all:
        lim_flowables = [Paragraph("Limitations & Notes", h1_style)]
        for lim in limitations_all:
            lim_flowables.append(Paragraph(f"• {escape(lim)}", body_style))
        lim_flowables.append(Spacer(1, 10))
        story.append(KeepTogether(lim_flowables))

    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer.read()
